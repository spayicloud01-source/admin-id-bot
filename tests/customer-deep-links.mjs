import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const html=readFileSync(new URL('../customer.html', import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'customer inline script exists');
new Function(script);
assert.match(script,/function actionFromLink\(\)/);
assert.match(script,/VALID_ACTIONS\.includes\(requested\)/);
assert.match(script,/if\(requested\)selectAction\(requested\)/);
assert.match(script,/action==='status'/);
assert.match(script,/\['payment','close','fine'\]/);
assert.match(script,/kind==='fine'\?account\.lateFee/);
assert.match(html,/data-action="fine"/);
assert.match(html,/id="discountPanel"/);
assert.match(html,/id="discountCloseAmount"/);
assert.match(script,/discountPanel'\)\.classList\.remove\('hidden'\)/);
assert.match(script,/discountContactBtn'\)\.onclick=\(\)=>selectAction\('admin'\)/);
assert.match(script,/action==='fine'&&/);
assert.match(script,/action==='admin'/);
const contactBlock=script.slice(script.indexOf('function selectAction('),script.indexOf('function render('));
assert.doesNotMatch(contactBlock,/\/api\/customer\/contact/,'navigation must never send LINE automatically');
assert.match(script,/contactAdminBtn'\)\.onclick=async/);
assert.match(html,/id="contactPanel"/);
assert.match(html,/id="dueCountdown"/);
assert.match(script,/dueCountdown\x27\)\.textContent=account\.dueMessage/);
assert.match(html,/status-panel strong/);
assert.match(html,/\.status-panel #dueCountdown,\.status-panel #dueMessage\{color:#ffe16b\}/,'not overdue: yellow due text');
assert.match(html,/\.status-panel\.overdue #dueCountdown,\.status-panel\.overdue #dueMessage\{color:#ff8a8a\}/,'overdue: red due text');
assert.match(script,/classList\.toggle\('overdue',account\.overdueDays>0\)/,'red condition is backend overdueDays');
assert.match(script,/action===\x27status\x27/);
console.log('PASS: all customer LINE deep links support authenticated navigation, without automatic LINE contact');
